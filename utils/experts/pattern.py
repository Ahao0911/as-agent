    def analyze(self, data):
        """
        三指标联动分析（图形买点体系完整体系）
        data: dict，含 df（DataFrame: high/low/close/volume，升序）
        返回: dict 完整分析
        """
        from utils.indicators import analyze_dual_line, analyze_trend
        from utils.brick import brick_signal
        from utils.needle20 import needle20_signal
        from utils.key_kline import analyze_key_klines, is_junk_time

        df = data.get("df") if isinstance(data, dict) else data
        if df is None:
            return {"error": "无K线数据，无法计算指标"}

        dual = analyze_dual_line(df)
        trend = analyze_trend(df)
        brick = brick_signal(df, dual)
        needle = needle20_signal(df, dual)
        key_kline = analyze_key_klines(df, dual)
        junk, junk_reason = is_junk_time(df, dual)

        result = {"黄白线": dual, "砖型图": brick, "单针下20": needle, "关键K线": key_kline, "垃圾时间": junk, "垃圾时间原因": junk_reason}
        if isinstance(trend, dict):
            result["趋势"] = trend

        # 综合结论
        bull = dual.get("多头区间", False)
        buy_signal = any([needle.get("白线下20"), needle.get("四线归零"),
                          needle.get("白穿红线"), needle.get("白穿黄线")])
        brick_ok = brick.get("绿翻强红") or brick.get("今日翻红")
        if bull and buy_signal and brick_ok:
            result["综合"] = "★★★ 三重共振：多头环境+回调到位+动量翻红 → 高胜率买点"
        elif bull and buy_signal:
            result["综合"] = "★★ 双确认：多头环境+单针下20买点 → 等砖型图翻红确认"
        elif bull and brick_ok:
            result["综合"] = "★★ 双确认：多头环境+砖型图翻红 → 位置偏高谨慎追"
        elif not bull:
            result["综合"] = "✗ 空头环境：买点信号降级为反弹，不重仓快进快出"
        else:
            result["综合"] = "○ 观望：无买点信号，等待回调到位"
        # 关键K线补充
        if junk:
            result["综合"] += f" | 垃圾时间: {junk_reason}"
        if key_kline and key_kline.get("检测到关键K线", 0) > 0:
            result["综合"] += f" | 关键K线{key_kline['检测到关键K线']}根，最近{key_kline.get('最近关键K线',{}).get('原因','')}"
        return result
